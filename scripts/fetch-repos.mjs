// Fetch public repo metadata for a GitHub user and write src/data/repos.{json,js}.
// Usage: node scripts/fetch-repos.mjs [login]   (default: owner from src/site.config.json)
// Honours GITHUB_TOKEN when present (raises the API limit from 60/h to 5000/h).

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const here = import.meta.dirname;
const root = resolve(here, '..');
const configPath = resolve(root, 'src/site.config.json');
const config = existsSync(configPath) ? JSON.parse(readFileSync(configPath, 'utf8')) : {};
const USER = process.argv[2] || config.owner;

const dataDir = resolve(root, 'src/data');
const jsonOut = resolve(dataDir, 'repos.json');
const jsOut = resolve(dataDir, 'repos.js');

const headers = { 'User-Agent': 'waw-portfolio-build', Accept: 'application/vnd.github+json' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

async function get(url, accept) {
  const res = await fetch(url, { headers: accept ? { ...headers, Accept: accept } : headers });
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return accept ? res.text() : res.json();
}

/** Reduce a README to a single useful plain-text paragraph. */
function summarize(readme) {
  if (!readme) return null;
  const text = readme
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/^\s*\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)\s*$/gm, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/^\s{0,3}#{1,6}\s*/gm, '')
    .replace(/^\s*[>\-*+]\s+/gm, ' ')
    .replace(/[*_`~]/g, ' ')
    .replace(/\|/g, ' ');

  for (const block of text.split(/\n\s*\n/)) {
    const clean = block.replace(/\s+/g, ' ').trim();
    if (clean.length < 40) continue;
    if (/^(badge|license|build|ci)\b/i.test(clean)) continue;
    return clean.length > 420 ? `${clean.slice(0, 418).trimEnd()}…` : clean;
  }
  return null;
}

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let cursor = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (cursor < items.length) {
        const i = cursor++;
        results[i] = await fn(items[i], i);
      }
    }),
  );
  return results;
}

console.log(`→ https://api.github.com/users/${USER}`);
const profile = await get(`https://api.github.com/users/${USER}`);
if (!profile) {
  console.error(`✗ GitHub user not found: ${USER}`);
  process.exit(1);
}

let repos = [];
for (let page = 1; page <= 3; page++) {
  const batch = await get(`https://api.github.com/users/${USER}/repos?per_page=100&page=${page}&sort=updated`);
  if (!batch?.length) break;
  repos = repos.concat(batch);
}

const kept = repos.filter((r) => !r.fork && !r.archived);
console.log(`→ ${repos.length} repos · ${kept.length} kept (forks/archived dropped)`);

const enriched = await mapLimit(kept, 4, async (r) => {
  let readme = null;
  try {
    readme = await get(`https://api.github.com/repos/${r.full_name}/readme`, 'application/vnd.github.raw+json');
  } catch (err) {
    console.warn(`  ! readme ${r.full_name}: ${err.message}`);
  }
  return {
    name: r.name,
    description: r.description,
    readmeSummary: summarize(readme),
    url: r.html_url,
    homepage: r.homepage || null,
    language: r.language,
    topics: r.topics ?? [],
    stars: r.stargazers_count,
    forks: r.forks_count,
    sizeKb: r.size,
    createdAt: r.created_at,
    updatedAt: r.pushed_at,
    license: r.license?.spdx_id ?? null,
    isProfileRepo: r.name.toLowerCase() === `${USER.toLowerCase()}.github.io`,
  };
});

enriched.sort((a, b) => b.stars - a.stars || new Date(b.updatedAt) - new Date(a.updatedAt));

const payload = {
  generatedAt: new Date().toISOString(),
  user: {
    login: profile.login,
    name: profile.name,
    bio: profile.bio,
    avatar: profile.avatar_url,
    blog: profile.blog || null,
    location: profile.location || null,
    followers: profile.followers,
    following: profile.following,
    publicRepos: profile.public_repos,
    htmlUrl: profile.html_url,
    createdAt: profile.created_at,
  },
  repos: enriched,
};

mkdirSync(dataDir, { recursive: true });
writeFileSync(jsonOut, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
writeFileSync(
  jsOut,
  `// GENERATED by scripts/fetch-repos.mjs on ${payload.generatedAt} — do not hand-edit.\n` +
    `// Regenerate with: npm run fetch:repos\n\n` +
    `export default ${JSON.stringify(payload, null, 2)};\n`,
  'utf8',
);

console.log(`✓ wrote ${jsonOut}`);
console.log(`✓ wrote ${jsOut}`);
for (const r of enriched) {
  const src = r.description ? 'desc' : r.readmeSummary ? 'readme' : 'EMPTY';
  console.log(`  - ${r.name} · ${r.language ?? '—'} · ★${r.stars} · [${src}]`);
}
const blanks = enriched.filter((r) => !r.description && !r.readmeSummary);
if (blanks.length) {
  console.warn(`\n! ${blanks.length} repo(s) without copy: ${blanks.map((r) => r.name).join(', ')}`);
  console.warn('  Add hand-written blurbs to CURATED in src/data/projects.js');
}
